"""Embeds the web UI from web/ into the firmware.

Every file in web/ is gzipped and written to src/generated/web_assets.h as a byte
array with its URL path, MIME type and an ETag derived from the file content.
JavaScript, CSS and HTML lose comments and indentation first (shrink below). The
header is rewritten only when its content changes, so an unchanged UI does not
rebuild the web server. Only net/WebServer.cpp may include it: the arrays are
static and would be copied into every file that includes the header.

Runs as a PlatformIO pre-script (extra_scripts = pre:scripts/embed_web.py) and can
also be run by hand from the project root: python scripts/embed_web.py
"""

import gzip
import hashlib
import os
import re
import sys

# Explicit list: an unknown extension stops the build instead of being served with
# a guessed type.
MIME_TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json; charset=utf-8",
    ".txt": "text/plain; charset=utf-8",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".webmanifest": "application/manifest+json",
}

# Text files outside text/* whose line endings are normalized as well.
TEXT_EXTRA = {".json", ".svg", ".webmanifest"}

# Gzipped size goal for the whole UI. Only a warning.
SIZE_GOAL = 25 * 1024

SAFE_PATH = re.compile(r"^/[A-Za-z0-9._/-]+$")


# Files whose comments and indentation are removed before gzip. Only safe
# steps: line breaks stay (JavaScript inserts semicolons at them), only whole-line
# "//" comments go, and the web/ sources keep no multi-line template literals or
# <pre> blocks whose indentation would matter.
SHRINK = {".js", ".css", ".html"}


def shrink(ext, text):
    if ext == ".css":
        text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    lines = []
    for line in text.split("\n"):
        stripped = line.strip()
        if not stripped or (ext != ".css" and stripped.startswith("//")):
            continue
        lines.append(stripped)
    return "\n".join(lines) + "\n"


def collect(web_dir):
    """Returns (url path, file path) pairs sorted by URL path."""
    files = []
    for root, dirs, names in os.walk(web_dir):
        dirs[:] = sorted(d for d in dirs if not d.startswith("."))
        for name in sorted(names):
            if name.startswith("."):
                continue
            full = os.path.join(root, name)
            url = "/" + os.path.relpath(full, web_dir).replace(os.sep, "/")
            files.append((url, full))
    return sorted(files)


def render(assets):
    lines = [
        "// Generated by scripts/embed_web.py from web/. Do not edit.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace ledframe {",
        "namespace web {",
        "",
        "struct WebAsset {",
        "  const char* path;  // URL path, e.g. \"/index.html\"",
        "  const char* mime;",
        "  const char* etag;  // quoted, as sent in the ETag header",
        "  const uint8_t* data;  // gzip",
        "  size_t size;",
        "};",
        "",
    ]
    for i, asset in enumerate(assets):
        lines.append(f"// {asset['path']}: {asset['raw']} B, gzip {len(asset['gzip'])} B")
        lines.append(f"static const uint8_t kAsset{i}[] = {{")
        data = asset["gzip"]
        for start in range(0, len(data), 16):
            chunk = ", ".join(f"0x{b:02x}" for b in data[start:start + 16])
            lines.append(f"    {chunk},")
        lines.append("};")
        lines.append("")
    lines.append("static constexpr WebAsset kWebAssets[] = {")
    for i, asset in enumerate(assets):
        lines.append(f"    {{\"{asset['path']}\", \"{asset['mime']}\", \"\\\"{asset['etag']}\\\"\", "
                     f"kAsset{i}, sizeof(kAsset{i})}},")
    lines.append("};")
    lines.append("static constexpr size_t kWebAssetCount = sizeof(kWebAssets) / sizeof(kWebAssets[0]);")
    lines.append("")
    lines.append("}  // namespace web")
    lines.append("}  // namespace ledframe")
    lines.append("")
    return "\n".join(lines)


def write_if_changed(path, content):
    """Writes the file only when its content differs. Returns True when written."""
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8", newline="") as f:
            if f.read() == content:
                return False
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    return True


def embed(project_dir):
    web_dir = os.path.join(project_dir, "web")
    out_path = os.path.join(project_dir, "src", "generated", "web_assets.h")
    files = collect(web_dir) if os.path.isdir(web_dir) else []
    if not files:
        sys.exit(f"embed_web: no files in {web_dir}")

    assets = []
    for url, full in files:
        ext = os.path.splitext(full)[1].lower()
        if ext not in MIME_TYPES:
            sys.exit(f"embed_web: {url}: unknown file type '{ext}', add it to MIME_TYPES")
        if not SAFE_PATH.match(url):
            sys.exit(f"embed_web: {url}: use only letters, digits, '.', '_', '-' and '/'")
        with open(full, "rb") as f:
            raw = f.read()
        if MIME_TYPES[ext].startswith("text/") or ext in TEXT_EXTRA:
            # A Windows checkout (core.autocrlf) has CRLF; the same UI must give the
            # same bytes and ETag on every machine.
            raw = raw.replace(b"\r\n", b"\n")
        if ext in SHRINK:
            raw = shrink(ext, raw.decode("utf-8")).encode("utf-8")
        assets.append({
            "path": url,
            "mime": MIME_TYPES[ext],
            # mtime=0 keeps the output identical for identical input.
            "gzip": gzip.compress(raw, compresslevel=9, mtime=0),
            "etag": hashlib.sha256(raw).hexdigest()[:16],
            "raw": len(raw),
        })

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    # The directory ignores itself. A line in the root .gitignore would not last:
    # the PlatformIO IDE rewrites that file from its template.
    write_if_changed(os.path.join(os.path.dirname(out_path), ".gitignore"),
                     "# Build output of scripts/embed_web.py.\n*\n")
    content = render(assets)
    changed = write_if_changed(out_path, content)

    total = sum(len(a["gzip"]) for a in assets)
    state = "updated" if changed else "unchanged"
    print(f"embed_web: {len(assets)} files, {total} B gzip, web_assets.h {state}")
    if total > SIZE_GOAL:
        print(f"embed_web: warning: {total} B gzip is above the {SIZE_GOAL} B goal")


try:
    Import("env")  # noqa: F821 - provided by PlatformIO (SCons)
except NameError:
    env = None

if env is not None:
    embed(env.subst("$PROJECT_DIR"))
elif __name__ == "__main__":
    embed(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
